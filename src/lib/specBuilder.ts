import type { PipelineRun } from '../types/autodev';
import { buildIterationArtifactPaths } from './iterationContext';

export interface PrArtifacts {
  specJsonPath: string;
  specJsonContent: string;
  archivedSpecPath: string;
  prdMdPath: string;
  prdMdContent: string;
  archivedPrdPath: string;
  e2eTestPath: string;
  e2eTestContent: string;
  prTitle: string;
  prBody: string;
}

const READONLY_BANNER_MARKER = 'AUTODEV-READONLY-TEST-CONTRACT';

export function isEmptyGitHubRepoError(message: string): boolean {
  const lower = message.toLowerCase();
  return (
    lower.includes('repository is empty') ||
    lower.includes('(409)') ||
    (lower.includes('(404)') && lower.includes('not found'))
  );
}

export function buildBootstrapReadmeContent(owner: string, repo: string): string {
  return [
    `# ${repo}`,
    ``,
    `Repository base branch initialized by AutoDev Studio (\`${owner}/${repo}\`).`,
    ``,
  ].join('\n');
}

export function ensureReadOnlyTestHeader(code: string, runId: string, prdTitle: string): string {
  const trimmed = code.trim();
  if (trimmed.includes(READONLY_BANNER_MARKER)) {
    return `${trimmed}\n`;
  }
  const header = [
    `/**`,
    ` * ${READONLY_BANNER_MARKER}`,
    ` * Generated by AutoDev Studio (QA Spec Agent -> QA Critic Agent).`,
    ` * Run ID: ${runId}`,
    ` * Requirement: ${prdTitle}`,
    ` *`,
    ` * READ-ONLY CONTRACT: Coding agents and GitHub Actions execution sandboxes`,
    ` * MUST NOT weaken or modify assertions in this file. Fix implementation code`,
    ` * until all test assertions pass.`,
    ` */`,
    ``,
  ].join('\n');

  return `${header}${trimmed}\n`;
}

export function buildPrArtifacts(run: PipelineRun): PrArtifacts {
  const paths = buildIterationArtifactPaths(run.id);

  const specPayload = {
    schemaVersion: '1.1',
    generatedBy: 'AutoDev Studio',
    runId: run.id,
    createdAt: run.createdAt,
    repository: run.repoFullName,
    baseBranch: run.defaultBranch,
    baseCommitSha: run.repoContext?.headSha || undefined,
    e2eTestPath: paths.e2eTestPath,
    archivedSpecPath: paths.archivedSpecPath,
    prdTitle: run.prdTitle,
    architecture: {
      summary: run.architect.architectureSummary,
      techDecisions: run.architect.techDecisions,
    },
    ambiguities: run.architect.ambiguities,
    apiContracts: run.architect.apiContracts,
    tasks: run.architect.tasks,
    qaSpec: {
      coverageNotes: run.qaSpec.coverageNotes,
      initialApiTestCount: run.qaSpec.apiTestChecklist.length,
    },
    qaCritic: {
      reviewSummary: run.qaCritic.reviewSummary,
      findings: run.qaCritic.findings,
      finalApiTestChecklist: run.qaCritic.finalApiTestChecklist,
    },
  };

  const specJsonContent = `${JSON.stringify(specPayload, null, 2)}\n`;

  const ambiguitiesSection =
    run.architect.ambiguities.length > 0
      ? run.architect.ambiguities
          .map(
            (a) =>
              `- **[${a.severity.toUpperCase()}] ${a.title}**: ${a.detail}\n  - 澄清建议：${a.clarificationSuggestion}`
          )
          .join('\n')
      : '- 未发现明显逻辑漏洞或歧义。';

  const prdMdContent = [
    `# ${run.prdTitle}`,
    ``,
    `> Generated by AutoDev Studio · Run ID: \`${run.id}\` · Target: \`${run.repoFullName}\`${
      run.repoContext?.headSha ? ` · Base: \`${run.repoContext.headSha.slice(0, 7)}\`` : ''
    }`,
    ``,
    `## 原始需求描述 (PRD)`,
    ``,
    run.prdContent.trim(),
    ``,
    `## 架构分析摘要`,
    ``,
    run.architect.architectureSummary.trim(),
    ``,
    `## 需求歧义与澄清记录`,
    ``,
    ambiguitiesSection,
    ``,
  ].join('\n');

  const e2eTestContent = ensureReadOnlyTestHeader(
    run.qaCritic.finalE2eTestCode,
    run.id,
    run.prdTitle
  );

  const taskSummaryLines = run.architect.tasks
    .map((task) => {
      const deps = task.dependsOn.length > 0 ? ` (依赖: ${task.dependsOn.join(', ')})` : '';
      return `- [ ] \`${task.id}\` **${task.title}** [${task.module} · ${task.estimatedComplexity}]${deps}`;
    })
    .join('\n');

  const findingsSummary =
    run.qaCritic.findings.length > 0
      ? run.qaCritic.findings
          .map((f) => `- [${f.severity.toUpperCase()}/${f.category}] ${f.issue}`)
          .join('\n')
      : '- QA Critic 复核通过，无高危遗漏项。';

  const prTitle = `[AutoDev Spec] ${run.prdTitle}`;
  const prBody = [
    `## AutoDev Studio — 增量迭代规格与只读测试集 (Draft PR)`,
    ``,
    `本 Draft PR 由 **AutoDev Studio** 自动生成，基于最新 \`${run.defaultBranch}\` 代码上下文完成架构拆解与独立 QA Critic 评审。`,
    ``,
    `### 提交制品（保留历次回归测试）`,
    `- \`${paths.prdMdPath}\` & \`${paths.archivedPrdPath}\` — 本轮结构化需求文档与归档`,
    `- \`${paths.specJsonPath}\` & \`${paths.archivedSpecPath}\` — 架构方案、接口契约 (${run.architect.apiContracts.length} 项) 与原子任务树 (${run.architect.tasks.length} 项)`,
    `- \`${paths.e2eTestPath}\` — 本轮独立只读 Playwright E2E 测试脚本（不覆盖历史回归测试）`,
    ``,
    `### 原子任务清单`,
    taskSummaryLines,
    ``,
    `### QA Critic 独立评审摘要`,
    `${run.qaCritic.reviewSummary}`,
    ``,
    findingsSummary,
    ``,
    `---`,
    `Run ID: \`${run.id}\` | Generated at: ${run.createdAt}`,
  ].join('\n');

  return {
    specJsonPath: paths.specJsonPath,
    specJsonContent,
    archivedSpecPath: paths.archivedSpecPath,
    prdMdPath: paths.prdMdPath,
    prdMdContent,
    archivedPrdPath: paths.archivedPrdPath,
    e2eTestPath: paths.e2eTestPath,
    e2eTestContent,
    prTitle,
    prBody,
  };
}

